def _normalize_query(q: str) -> str:
    return re.sub(r"\s+", " ", q.strip().lower())


def analyze_candidate_genius(
    query_name: str,
    constellations: List[Dict[str, Any]],
    wiki_notes: Optional[List[Dict[str, Any]]] = None,
    custom_hint: str = "",
) -> Dict[str, Any]:
    norm = _normalize_query(query_name)
    clean_display = query_name.strip() or "미상 탐구자"

    # 0. Check if already in an existing constellation!
    already_in: Optional[Dict[str, Any]] = None
    existing_genius_obj: Optional[Dict[str, Any]] = None
    for c in constellations:
        for g in c.get("geniuses", []):
            g_norm = _normalize_query(g["name"])
            if len(norm) >= 2 and (norm in g_norm or g_norm in norm):
                already_in = {
                    "constellation_id": c["id"],
                    "constellation_name": c["name"],
                    "genius_id": g["id"],
                }
                existing_genius_obj = g
                break
        if already_in:
            break

    # 1. Search offline Curated Master Archive (exact key or substring match)
    matched_entry: Optional[Dict[str, Any]] = None
    for entry in CURATED_GENIUS_ARCHIVE:
        for k in entry["keys"]:
            if norm == k or (len(norm) >= 2 and (norm in k or k in norm)):
                matched_entry = entry
                break
        if matched_entry:
            break

    # 2. Check if user's own Markdown Wiki Vault mentions this figure!
    vault_hits: List[str] = []
    if wiki_notes and len(norm) >= 2:
        for n in wiki_notes:
            blob = f"{n.get('title', '')} {n.get('content', '')}".lower()
            if norm in blob:
                vault_hits.append(n["title"])

    if matched_entry:
        raw_scores = dict(matched_entry["domain_scores"])
        source_mode = "curated_archive"
        source_badge = "📚 내장 역사·과학 검증 아카이브 일치"
        name = matched_entry["name"]
        en_name = matched_entry["en_name"]
        emoji = matched_entry["emoji"]
        era_field = matched_entry["era_field"]
        lens = matched_entry["lens"]
        summary = matched_entry["summary"]
        achievements = list(matched_entry["achievements"])
        if vault_hits:
            achievements.append(f"내 마크다운 위키 기억망(『{vault_hits[0]}』)과도 직접 연결된 핵심 인물")
        proof = matched_entry["proof_of_genius"]
        strengths = matched_entry["genius_strengths"]
        limitations = matched_entry["limitations"]
        credo = matched_entry["credo"]
    elif existing_genius_obj and already_in:
        raw_scores = {already_in["constellation_id"]: 96}
        for cid in DOMAIN_KEYWORD_HINTS:
            raw_scores.setdefault(cid, 80)
        source_mode = "active_member"
        source_badge = f"🌌 현재 [{already_in['constellation_name']}] 소속 활동 중"
        name = existing_genius_obj["name"]
        en_name = "Active Constellation Mentor"
        emoji = existing_genius_obj.get("emoji", "🌟")
        era_field = f"{already_in['constellation_name']} 핵심 스승"
        lens = existing_genius_obj.get("lens", "핵심 원리")
        summary = f"현재 우리 두뇌의 [{already_in['constellation_name']}]에서 '{lens}' 관점을 담당하고 있는 핵심 천재입니다. 다른 영역 성좌로 재배치(이동)할 수 있습니다!"
        achievements = [
            f"전문 관점: {lens}",
            f"원탁 토론 역할: {existing_genius_obj.get('rebuttal_style', '성좌 내부 상호 검증')}",
        ]
        proof = f"'{lens}' 원리를 4비트 양자화 시냅스로 제공하여 5인 꼬마 뉴런의 오판율을 낮추고 있습니다."
        strengths = existing_genius_obj.get("strengths") or f"'{lens}' 영역에서 타협 없는 정밀 기준을 제시함."
        limitations = existing_genius_obj.get("limitations") or "단일 전문 관점에 집중하므로 다른 성좌로 파견하거나 복합 성좌 토론을 열면 시너지가 더욱 커짐."
        credo = existing_genius_obj.get("credo", "")
    else:
        # Dynamic honest analysis (Feynman zero-hallucination rule: never invent fake dates/awards!)
        combined_text = f"{clean_display} {custom_hint}".strip()
        raw_scores = {}
        for cid, kws in DOMAIN_KEYWORD_HINTS.items():
            hits = sum(1 for kw in kws if kw in combined_text.lower())
            seed_bump = (hashlib.md5(f"{clean_display}:{cid}".encode("utf-8")).digest()[0] % 14)
            raw_scores[cid] = min(96, 68 + hits * 9 + seed_bump)

        source_mode = "dynamic_custom"
        source_badge = "🧭 맞춤 인물 분석 모드 (환각 방지 정직 검증)"
        name = clean_display
        en_name = "Custom Recruited Thinker"
        emoji = "🌟"
        era_field = custom_hint.strip()[:36] if custom_hint.strip() else "주인님 발굴 전문 지성"
        lens = custom_hint.strip()[:28] if custom_hint.strip() else f"{clean_display} 고유 통찰 관점"
        summary = (
            f"'{clean_display}' 인물에 대해 거짓 연도나 허위 일화를 지어내지 않고(환각 0% 원칙), "
            f"입력된 단서와 내 위키 기억망({len(vault_hits)}건 일치)을 바탕으로 성좌 적합도와 상호보완 포인트를 분석했습니다."
        )
        achievements = [
            f"핵심 탐구 영역: {custom_hint.strip() if custom_hint.strip() else '복합 문제 해결 및 독자적 관점 제시'}",
            (
                f"내 마크다운 위키 노트 『{vault_hits[0]}』에서 관련 맥락 확인됨"
                if vault_hits
                else "오프라인 기본 사전 외 인물 — 아래 설명란에 업적·특징 한 줄을 덧붙이면 성좌 적합도가 더욱 정밀해집니다!"
            ),
        ]
        proof = f"기존 성좌 천재들과 다른 고유 시각('{lens}')을 원탁 담론에 공급해 집단 사고의 사각지대를 넓혀 줍니다."
        strengths = f"특화 관점({lens})에서 문제를 새롭게 재정의하고 기존 성좌의 고정관념에 신선한 반론을 제기함."
        limitations = "단일 인물 관점만으로는 모든 경계 조건(메모리 한계·역공학 함정·확률 오차)을 동시에 덮기 어려우므로, 성좌 내 다른 천재들과 상호 검증할 때 진가가 발휘됨."
        credo = (
            custom_hint.strip()
            if len(custom_hint.strip()) >= 12
            else f"{clean_display}의 시선으로 당연한 전제를 다시 의심하고, 다른 천재들과 부딪히며 가장 단단한 해법을 빚어냅시다!"
        )

    # Score against ALL currently existing constellations (including user-created custom constellations!)
    const_rankings: List[Dict[str, Any]] = []
    blob_for_custom = f"{name} {era_field} {lens} {strengths} {credo}".lower()
    for c in constellations:
        cid = c["id"]
        if cid in raw_scores:
            sc = raw_scores[cid]
        else:
            # Custom user-created constellation: match domain tokens!
            c_tokens = re.findall(r"[가-힣a-z0-9]{2,}", f"{c['name']} {c.get('domain_mission', '')}".lower())
            overlap = sum(1 for t in c_tokens if t in blob_for_custom and t != "성좌")
            sc = min(97, 74 + overlap * 10)
        const_rankings.append(
            {
                "id": cid,
                "name": c["name"],
                "icon": c.get("icon", "🌌"),
                "color": c.get("color", "#818cf8"),
                "fit_pct": sc,
            }
        )

    const_rankings.sort(key=lambda x: x["fit_pct"], reverse=True)
    best = const_rankings[0] if const_rankings else {"id": "const_truth", "name": "제1원리·진실검증 성좌", "icon": "🔬", "fit_pct": 90}
    runner_up = const_rankings[1] if len(const_rankings) > 1 else best

    placement_reason = (
        f"업적과 사고방식을 5대 성좌 축으로 분석한 결과, **{best['icon']} {best['name']}**(적합도 **{best['fit_pct']}%**)에서 "
        f"천재성이 가장 강력하게 발휘되며, 기록된 한계점 또한 해당 성좌의 동료 천재들이 완벽히 상호 보완해 줍니다! "
        f"(차선 추천: {runner_up['icon']} {runner_up['name']} {runner_up['fit_pct']}% — 원하시면 아래에서 다른 성좌로 자유롭게 바꿔 배치할 수 있습니다.)"
    )

    return {
        "query": query_name,
        "source_mode": source_mode,
        "source_badge": source_badge,
        "already_in": already_in,
        "name": name,
        "en_name": en_name,
        "emoji": emoji,
        "era_field": era_field,
        "lens": lens,
        "summary": summary,
        "achievements": achievements,
        "proof_of_genius": proof,
        "genius_strengths": strengths,
        "limitations": limitations,
        "credo": credo,
        "recommended_constellation": best,
        "constellation_rankings": const_rankings,
        "placement_reason": placement_reason,
    }
